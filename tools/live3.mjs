import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const PORT = 9372;
const proc = spawn(CHROME, ['--headless=new','--disable-gpu','--hide-scrollbars','--no-first-run','--remote-debugging-port='+PORT,'--user-data-dir='+(process.env.TEMP||'.')+'/cr-cdp-live3'], { stdio: 'ignore' });
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
await sleep(1500);
const v = await (await fetch('http://127.0.0.1:'+PORT+'/json/version')).json();
const ws = new WebSocket(v.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let seq = 0; const pending = new Map(); const errors = [];
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); return; } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); };
const send = (method, params = {}, sessionId) => new Promise((resolve) => { const id = ++seq; pending.set(id, resolve); ws.send(JSON.stringify({ id, method, params, sessionId })); });
const { result: { targetId } } = await send('Target.createTarget', { url: 'about:blank' });
const { result: { sessionId } } = await send('Target.attachToTarget', { targetId, flatten: true });
await send('Page.enable', {}, sessionId);
await send('Runtime.enable', {}, sessionId);
await send('Emulation.setDeviceMetricsOverride', { width: 430, height: 932, deviceScaleFactor: 2, mobile: true }, sessionId);
const ev = async (expr) => {
  const r = await send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true }, sessionId);
  return r.result && r.result.result ? r.result.result.value : null;
};
await send('Page.navigate', { url: 'https://lulu3103.github.io/composition-correct/#/settings' }, sessionId);
await sleep(3500);
await ev('localStorage.clear(); 1');
await send('Page.reload', {}, sessionId);
await sleep(3000);
console.log('badge:', await ev('document.querySelector(".badge").textContent'));
console.log('options:', await ev('document.querySelectorAll("#provider-select option").length'));
console.log('save disabled:', await ev('document.querySelector("#save-btn").disabled'));
const res = await send('Page.captureScreenshot', { format: 'png' }, sessionId);
await fs.writeFile('shots/live-v3-settings.png', Buffer.from(res.result.data, 'base64'));
console.log('errors:', JSON.stringify(errors.slice(0, 4)));
ws.close(); proc.kill();
